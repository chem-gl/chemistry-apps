def molar_fractions(ph_value: float, pka_values: list[float]) -> list[float]:
    """Calcula f0..fn con la fórmula del manual, desplazando exponentes."""
    exponents: list[float] = [
        species_index * ph_value - math.fsum(pka_values[:species_index])
        for species_index in range(len(pka_values) + 1)
    ]
    peak: float = max(exponents)
    weights: list[float] = [10 ** (exponent - peak) for exponent in exponents]
    total: float = math.fsum(weights)
    return [weight / total for weight in weights]


def format_fraction(value: float) -> str:
    """Formatea una fracción sin perder los valores pequeños."""
    if value == 0.0:
        return "0"
    if abs(value) >= 0.0001:
        return f"{value:.4f}"
    return f"{value:.1e}"


def build_path(points: list[tuple[float, float]]) -> str:
    """Convierte una lista de puntos en un atributo `d` de SVG."""
    return " ".join(
        f"{'M' if index == 0 else 'L'}{x:.1f},{y:.1f}"
        for index, (x, y) in enumerate(points)
    )


def build_marcus_svg() -> str:
    """Genera el diagrama clásico de Marcus con dos parábolas desplazadas."""
    # Rango con margen: ambas parábolas entran completas en el encuadre.
    x_min, x_max = -0.25, 1.18
    energy_low, energy_high = -2.9, 7.4
    pad_left, pad_right, pad_top, pad_bottom = 42, 26, 22, 34
    plot_width = WIDTH - pad_left - pad_right
    plot_height = HEIGHT - pad_top - pad_bottom

    def to_x(value: float) -> float:
        return pad_left + (value - x_min) / (x_max - x_min) * plot_width

    def to_y(value: float) -> float:
        return (
            pad_top + (energy_high - value) / (energy_high - energy_low) * plot_height
        )

    xs = [
        x_min + (x_max - x_min) * index / (SAMPLE_COUNT - 1)
        for index in range(SAMPLE_COUNT)
    ]
    reactant_points = [(to_x(x), to_y(MARCUS_LAMBDA * x * x)) for x in xs]
    product_points = [
        (to_x(x), to_y(MARCUS_LAMBDA * (x - 1) ** 2 + MARCUS_DELTA_G)) for x in xs
    ]

    x_star = (MARCUS_LAMBDA + MARCUS_DELTA_G) / (2 * MARCUS_LAMBDA)
    barrier = (MARCUS_LAMBDA + MARCUS_DELTA_G) ** 2 / (4 * MARCUS_LAMBDA)

    axis_bottom = HEIGHT - pad_bottom
    zero_y = to_y(0.0)
    reactant_y = to_y(0.0)
    product_y = to_y(MARCUS_DELTA_G)
    reactant_at_one_y = to_y(MARCUS_LAMBDA)
    x_one = to_x(1.0)
    lambda_label_y = (reactant_at_one_y + product_y) / 2

    return f"""<svg viewBox="0 0 {WIDTH} {HEIGHT}" role="img" aria-label="Marcus free-energy parabolas crossing at ΔG‡ = {barrier:.2f} kcal/mol">
<line x1="{pad_left}" y1="{axis_bottom}" x2="{WIDTH - pad_right}" y2="{axis_bottom}" stroke="currentColor" stroke-width="1" opacity="0.35"/>
<line x1="{pad_left}" y1="{pad_top}" x2="{pad_left}" y2="{axis_bottom}" stroke="currentColor" stroke-width="1" opacity="0.35"/>
<line x1="{pad_left}" y1="{zero_y:.1f}" x2="{WIDTH - pad_right}" y2="{zero_y:.1f}" stroke="currentColor" stroke-width="0.8" opacity="0.15"/>
<path d="{build_path(reactant_points)}" fill="none" stroke="#6a4c93" stroke-width="2.4" stroke-linecap="round"/>
<path d="{build_path(product_points)}" fill="none" stroke="#0277bd" stroke-width="1.8" stroke-dasharray="6,4" stroke-linecap="round"/>
<line x1="{x_one:.1f}" y1="{reactant_at_one_y:.1f}" x2="{x_one:.1f}" y2="{product_y:.1f}" stroke="currentColor" stroke-width="1" stroke-dasharray="3,3" opacity="0.45"/>
<circle cx="{to_x(0.0):.1f}" cy="{reactant_y:.1f}" r="3" fill="#6a4c93"/>
<circle cx="{to_x(1.0):.1f}" cy="{product_y:.1f}" r="3" fill="#0277bd"/>
<circle cx="{to_x(x_star):.1f}" cy="{to_y(barrier):.1f}" r="3" fill="currentColor"/>
<text x="{to_x(0.0) + 6:.1f}" y="{reactant_y - 6:.1f}" font-size="10" fill="currentColor">R (0)</text>
<text x="{to_x(1.0) + 7:.1f}" y="{product_y - 7:.1f}" font-size="10" fill="currentColor">P ({MARCUS_DELTA_G:.2f})</text>
<text x="{to_x(x_star) + 10:.1f}" y="{to_y(barrier) + 4:.1f}" font-size="10" fill="currentColor">ΔG‡ = {barrier:.2f}</text>
<text x="{x_one - 6:.1f}" y="{lambda_label_y:.1f}" font-size="10" fill="currentColor" text-anchor="end">λ = {MARCUS_LAMBDA:.2f}</text>
<text x="{pad_left + 6:.1f}" y="{pad_top + 12:.1f}" font-size="10" fill="#0277bd">V_P (products)</text>
<text x="{WIDTH - pad_right - 6:.1f}" y="{to_y(MARCUS_LAMBDA * x_max**2) + 14:.1f}" font-size="10" fill="#6a4c93" text-anchor="end">V_R (reactants)</text>
<text x="{(pad_left + WIDTH - pad_right) / 2:.1f}" y="{HEIGHT - 6}" font-size="10" fill="currentColor" opacity="0.75" text-anchor="middle">reaction coordinate</text>
<text x="11" y="{pad_top + plot_height / 2:.1f}" font-size="9" fill="currentColor" opacity="0.7" text-anchor="middle" transform="rotate(-90 11 {pad_top + plot_height / 2:.1f})">energy</text>
</svg>"""


def build_molar_svg() -> str:
    """Genera las curvas de especiación f0..f3 frente a pH, evaluando la fórmula."""
    pad_left, pad_right, pad_top, pad_bottom = 38, 14, 42, 34
    plot_width = WIDTH - pad_left - pad_right
    plot_height = HEIGHT - pad_top - pad_bottom
    axis_bottom = HEIGHT - pad_bottom

    def to_x(ph_value: float) -> float:
        return (
            pad_left
            + (ph_value - MOLAR_PH_MIN) / (MOLAR_PH_MAX - MOLAR_PH_MIN) * plot_width
        )

    def to_y(fraction: float) -> float:
        return pad_top + (1.0 - fraction) * plot_height

    ph_values = [
        MOLAR_PH_MIN + (MOLAR_PH_MAX - MOLAR_PH_MIN) * index / (SAMPLE_COUNT - 1)
        for index in range(SAMPLE_COUNT)
    ]
    species_count = len(MOLAR_PKA) + 1
    curves = [
        [
            (to_x(ph_value), to_y(molar_fractions(ph_value, MOLAR_PKA)[species_index]))
            for ph_value in ph_values
        ]
        for species_index in range(species_count)
    ]
    curve_markup = "\n".join(
        f'<path d="{build_path(points)}" fill="none" stroke="{MOLAR_COLORS[species_index]}" '
        f'stroke-width="2"/>'
        for species_index, points in enumerate(curves)
    )

    legend_items: list[str] = []
    for species_index, label in enumerate(MOLAR_LABELS):
        column = species_index % 2
        row = species_index // 2
        legend_x = pad_left + column * 150
        legend_y = 14 + row * 14
        legend_items.append(
            f'<line x1="{legend_x}" y1="{legend_y - 3}" x2="{legend_x + 12}" y2="{legend_y - 3}" '
            f'stroke="{MOLAR_COLORS[species_index]}" stroke-width="2"/>'
            f'<text x="{legend_x + 16}" y="{legend_y}" font-size="9" fill="currentColor">{label}</text>'
        )
    legend_markup = "\n".join(legend_items)

    marker_x = to_x(7.4)
    y_tick_markup = "\n".join(
        f'<text x="{pad_left - 4}" y="{to_y(value) + 3:.1f}" font-size="8" fill="currentColor" '
        f'opacity="0.7" text-anchor="end">{label}</text>'
        for value, label in ((0.0, "0"), (0.5, "0.5"), (1.0, "1"))
    )

    return f"""<svg viewBox="0 0 {WIDTH} {HEIGHT}" role="img" aria-label="Molar fraction curves f0 to f3 versus pH with a marker at pH 7.4">
<line x1="{pad_left}" y1="{axis_bottom}" x2="{WIDTH - pad_right}" y2="{axis_bottom}" stroke="currentColor" stroke-width="1" opacity="0.35"/>
<line x1="{pad_left}" y1="{pad_top}" x2="{pad_left}" y2="{axis_bottom}" stroke="currentColor" stroke-width="1" opacity="0.35"/>
{y_tick_markup}
<line x1="{marker_x:.1f}" y1="{pad_top}" x2="{marker_x:.1f}" y2="{axis_bottom}" stroke="currentColor" stroke-width="1" stroke-dasharray="3,3" opacity="0.45"/>
<text x="{marker_x + 3:.1f}" y="{pad_top - 4}" font-size="8" fill="currentColor" opacity="0.75">pH 7.4</text>
{curve_markup}
{legend_markup}
<text x="{to_x(0.0):.1f}" y="{axis_bottom + 12}" font-size="8" fill="currentColor" opacity="0.7" text-anchor="middle">0</text>
<text x="{to_x(7.0):.1f}" y="{axis_bottom + 12}" font-size="8" fill="currentColor" opacity="0.7" text-anchor="middle">7</text>
<text x="{to_x(14.0):.1f}" y="{axis_bottom + 12}" font-size="8" fill="currentColor" opacity="0.7" text-anchor="middle">14</text>
<text x="{WIDTH - pad_right}" y="{HEIGHT - 6}" font-size="9" fill="currentColor" opacity="0.75" text-anchor="end">pH</text>
<text x="11" y="{pad_top + plot_height / 2:.1f}" font-size="9" fill="currentColor" opacity="0.7" text-anchor="middle" transform="rotate(-90 11 {pad_top + plot_height / 2:.1f})">fraction</text>
</svg>"""


def build_molar_example(locale: str) -> str:
    """Construye el HTML completo del ejemplo de fracciones molares."""
    copy = MOLAR_EXAMPLE_COPY[locale]
    fractions_at_74 = molar_fractions(7.4, MOLAR_PKA)
    ph_note = copy["ph74"].format(ha=fractions_at_74[2], h2a=fractions_at_74[1])

    header_cells = "".join(f"<th>{cell}</th>" for cell in MOLAR_TABLE_HEADERS)
    rows: list[str] = []
    for ph_value in MOLAR_PH_ROWS:
        fractions = molar_fractions(ph_value, MOLAR_PKA)
        cells = "".join(f"<td>{format_fraction(value)}</td>" for value in fractions)
        rows.append(
            f"<tr><td>{ph_value:.2f}</td>{cells}<td>{math.fsum(fractions):.4f}</td></tr>"
        )

    return (
        f"<h3>{copy['title']}</h3>\n"
        f"<p>{copy['inputs']}</p>\n"
        f"<h4>{copy['fractions_title']}</h4>\n"
        f"<p>{copy['formula']}</p>\n"
        f"{MOLAR_FORMULA_BLOCK}\n"
        f"<p>{copy['explanation']}</p>\n"
        "<table>\n"
        f"<thead><tr>{header_cells}</tr></thead>\n"
        "<tbody>\n" + "\n".join(rows) + "\n</tbody>\n</table>\n"
        f"<p>{ph_note}</p>\n"
        f"<p>{copy['caption']}</p>\n"
        f"{build_molar_svg()}\n"
        f"<p>{copy['closing']}</p>"
    )


def update_locale(locale_path: Path, *, dry_run: bool) -> bool:
    """Actualiza los diagramas de un catálogo i18n. Retorna si cambió."""
    payload = json.loads(locale_path.read_text(encoding="utf-8"))
    docs = payload.get("scientificDoc", {}).get("docs", {})
    if not isinstance(docs, dict) or not docs:
        return False

    changed = False
    marcus_section = docs.get("marcus", {}).get("example")
    if (
        isinstance(marcus_section, str)
        and "<svg" in marcus_section
        and "</svg>" in marcus_section
    ):
        start = marcus_section.index("<svg")
        end = marcus_section.index("</svg>") + len("</svg>")
        replacement = build_marcus_svg()
        if marcus_section[start:end] != replacement:
            docs["marcus"]["example"] = (
                marcus_section[:start] + replacement + marcus_section[end:]
            )
            changed = True

    locale = locale_path.stem
    molar_section = docs.get("molarFractions")
    if isinstance(molar_section, dict) and locale in MOLAR_EXAMPLE_COPY:
        replacement = build_molar_example(locale)
        if molar_section.get("example") != replacement:
            molar_section["example"] = replacement
            changed = True

    if changed and not dry_run:
        locale_path.write_text(
            json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Regenera los diagramas de los manuales (Marcus y fracciones molares)."
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="No escribe los catálogos."
    )
    arguments = parser.parse_args()

    locale_paths = sorted(I18N_DIR.glob("*.json"))
    if not locale_paths:
        print(f"No hay catálogos i18n en {I18N_DIR}")
        return 1

    changed = 0
    for locale_path in locale_paths:
        if update_locale(locale_path, dry_run=arguments.dry_run):
            changed += 1
            print(f"[docs] actualizado: {locale_path.name}")

    print(f"[docs] {changed}/{len(locale_paths)} catálogos regenerados.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
